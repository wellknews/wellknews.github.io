import { Delta } from '../../components/code/Delta'
import { Open } from '../../components/code/Open'
import { Passage } from '../../components/session/Passage'
import { Quiet } from '../../components/session/Quiet'
import { Scene } from '../../components/session/Scene'
import type { Code } from '../types'

/**
 * 새 CODE 기록을 쓸 때 이 파일을 복사한다.
 *
 *   1. code/무엇을-고쳤나.tsx 처럼 파일을 만든다 (파일명은 slug와 맞춘다)
 *   2. 아래 형태로 내용을 채운다
 *   3. content/code.ts의 codes 배열 맨 앞에 import해서 넣는다
 *
 * 세션의 템플릿과 규칙이 하나 다르다. 세션에서는 «없는 정보는 비워 둔다»가
 * 전부였는데, 여기서는 그 앞에 하나가 더 붙는다 — 있는 숫자는 지어내지
 * 않는다. revision과 diff는 git이 세어 준 값을 그대로 옮겨 적는 자리이고,
 * 어림잡은 값을 넣는 순간 이 게시판의 나머지 숫자도 전부 어림값이 된다.
 *
 * 지면
 *
 * 세션과 같은 무대를 쓴다. 문장과 장치를 Scene으로 나누고, 장면이 바뀌는
 * 자리에는 air를 준다. 여백이 이 공간의 속도이고, 코드 기록이라고 해서
 * 빽빽해도 되는 것이 아니다 — 한동안 이 게시판만 좁은 칼럼으로 두었다가
 * 사이트에서 가장 밀도 높은 페이지를 만든 적이 있다.
 *
 * 소제목(h3)을 쓰지 않는다. 이 공간의 어느 기록도 쓰지 않는다. 구간을
 * 나누는 것은 여백이고, 이름을 붙여야 할 자리에는 라벨 대신 크게 앉는
 * 한 문장을 놓는다(Passage tone="loud").
 *
 * 누구에게 쓰는가
 *
 * 앱을 써 본 적은 있지만 안이 어떻게 생겼는지는 모르는 사람에게 쓴다. 이 한
 * 줄이 낱말을 전부 정한다.
 *
 * 저장소 안에서 쓰는 이름을 그대로 내놓지 않는다. 워커, 후보풀, 원장, R8,
 * Composable, 프레임, 소스풀 같은 것들이다. 화면에 실제로 적혀 있는 낱말이
 * 있으면 그것을 쓰고(«앱 밖 렌더 알약»), 없으면 그 일이 일어나는 자리의 말로
 * 바꾼다(«굽는 동안 딴 일을 할 수 있다»). 바꿀 수 없는 이름은 처음 나올 때 한
 * 마디로 풀어 준다. 풀 수 없으면 빼는 쪽이 낫다 — 대개 그 낱말이 없어도 잰
 * 값은 그대로 읽힌다.
 *
 * 한동안 이 규칙이 없어서 기록 넷이 전부 «이미 안을 아는 사람끼리 하는 말»로
 * 쓰였다. 무엇이 달라졌는지를 앞에 놓아도 그 문장이 내부 이름으로 되어 있으면
 * 읽는 쪽에는 여전히 아무 그림도 서지 않는다.
 *
 * 무엇을 쓰는가
 *
 * 먼저 «무엇이 달라졌는가»를 쓴다. 앱을 켜는 사람의 화면에서 무엇이 새로
 * 보이고 무엇이 사라졌는지. 이것이 글의 앞이고 가운데다.
 *
 * 한동안 이 자리에 정확히 반대로 적혀 있었다 — «좋아진 것은 릴리스 노트가
 * 이미 갖고 있으니 여기서는 빼고, 잘못 짚은 쪽만 남겨라». 뜻은 옳았지만
 * 결과가 틀렸다. 그 규칙대로 쓰면 기록이 전부 «내가 어떻게 헤맸나»가 되고,
 * 정작 무엇이 바뀌었는지는 어느 글에도 서지 않는다. 노트와 기록이 각각
 * 반쪽씩 갖고 있으면 읽는 사람이 두 곳을 맞춰 봐야 하는데, 아무도 그러지
 * 않는다. 읽는 쪽에서 보면 그것은 기록이 아니라 남의 일기다.
 *
 * 그래서 순서를 뒤집는다.
 *
 *   앞   무엇이 달라졌는가. 기능의 이름이 아니라 그 기능을 쓰는 자리의
 *        말로 적는다. «워커로 옮겼다»가 아니라 «앱을 나가도 굽는다».
 *   뒤   그것을 만들면서 무엇을 잘못 짚었는지, 무엇을 재지 못했는지.
 *
 * 뒤쪽을 버리는 것이 아니다. 이 게시판이 릴리스 노트와 다른 이유는 여전히
 * 거기에 있다. 다만 그것은 앞쪽을 읽은 사람에게만 뜻이 있다 — 무엇을
 * 만들었는지 모르는 채로 «겨냥이 빗나갔다»를 읽으면 아무 그림도 서지 않는다.
 *
 * 릴리스 노트와 겹치는 것을 두려워하지 않는다. 겹치는 것이 낭비라고 보고
 * 겹치지 않게 쓴 결과가 더 나빴다.
 *
 * 합치고 고친 이야기는 이 게시판의 주인공이 아니다. 충돌이 없었다거나
 * 시험 몇 개가 깨졌다가 하는 것은, 그 일이 만들어진 것의 모양을 바꾼
 * 경우에만 적는다. 그렇지 않으면 한 줄로 줄이거나 빼도 된다.
 *
 * 조판 장치는 components/code/ 아래에 있다.
 *
 *   Delta   전과 후. 두 줄의 길이가 곧 변화다.
 *   Gate    통과한 검사들과, 검사가 없는 자리.
 *   Miss    겨눈 곳과 실제로 있던 곳.
 *   Prompt  답이 하나뿐인 물음. 눌러서 치울 수 있다.
 *   Open    못 쟀거나 하지 않은 것. 값 칸이 비어 있다.
 *   Flow    무엇이 어디를 거쳐 오는가. 바뀐 자리를 한 칸만 표시한다.
 *   Screens 화면이 어떻게 생겼는가. 스크린샷이 아니라 배치만 그린다.
 *   Stat    해시 범위와 diffstat. 머리의 표지 자리에 자동으로 앉는다.
 *
 * 앞의 다섯은 잰 값을 그리고, Flow와 Screens는 순서와 배치를 그린다. 뒤의 둘은
 * «이 게시판에 글자밖에 없다»는 말을 듣고 나중에 더한 것이다. 잰 값만 그리는
 * 장치로는 «그래서 화면이 어떻게 달라졌는데»에 답할 수 없었다.
 *
 * 새 장치를 만들기 전에 한 번 묻는다 — 이것이 문장을 대신하는가, 아니면
 * 문장 옆에 그림을 하나 더 두는 것인가. 뒤쪽이면 만들지 않는다.
 *
 * 이 파일은 codes 배열에 등록되어 있지 않으므로 사이트에 나오지 않는다.
 */
export const template: Code = {
  slug: 'slug',
  title: '제목',

  /** 저장소 이름. 주소가 아니라 부르는 이름이면 된다. */
  repo: 'repo',

  /** git이 말해 주는 그대로. 지어내지 않는다. */
  revision: { from: '0000000', to: '1111111' },
  diff: { commits: 1, added: 1, removed: 1 },

  meta: {
    date: '2026-01-01',
    type: 'PERFORMANCE',
  },

  /** 목록에 걸리는 한 줄. 이 업데이트로 무엇이 달라졌는지 한 줄로. */
  excerpt: '쓰는 사람의 화면에서 무엇이 달라졌는지 한 줄.',

  body: (
    <>
      {/*
        여는 장면에 무엇이 달라졌는지가 온다. 배경 설명이나 왜 시작했는지를
        앞에 두지 않는다 — 그것은 달라진 것을 읽은 다음에 뜻이 생긴다.
      */}
      <Scene>
        <Passage>
          <p>이 업데이트로 무엇이 달라졌는지 한두 단락.</p>
        </Passage>
      </Scene>

      {/* 구간이 바뀌는 자리. 소제목 대신 크게 앉는 한 문장을 놓는다. */}
      <Scene air>
        <Passage tone="loud">
          <p>달라진 것 중 가장 큰 하나를 말하는 문장.</p>
        </Passage>

        <Delta rows={[{ label: '무엇을 쟀는가', before: 100, after: 50, unit: 'ms' }]} />
      </Scene>

      {/* 여기부터 뒤쪽. 만들면서 무엇을 잘못 짚었는지. */}
      <Scene>
        <Passage>
          <p>단락.</p>
        </Passage>
      </Scene>

      <Scene air>
        <Open items={[{ what: '못 쟀거나 안 한 것', why: '왜 그런지' }]} />
      </Scene>

      {/* 색이 빠지는 자리. 연출을 더하는 대신 빼는 편이 맞는 대목에만 쓴다. */}
      <Quiet>
        <Passage>
          <p>닫는 문장.</p>
        </Passage>
      </Quiet>
    </>
  ),
}
