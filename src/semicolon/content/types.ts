import type { ReactNode } from 'react'

/**
 * 콘텐츠에 붙는 부가 정보.
 *
 * 모든 항목이 같은 메타데이터를 가질 필요는 없다. 없는 정보를 채우려고 값을
 * 지어내지 않고, 있는 정보라도 그 콘텐츠를 이해하는 데 필요할 때만 적는다.
 * 화면은 여기 실제로 들어온 것만 보여준다.
 */
export type Meta = {
  /** 'YYYY-MM-DD', 'YYYY-MM' 등 아는 만큼만. 화면에는 적은 그대로 나온다. */
  date?: string
  location?: string
  duration?: string
  type?: string
}

/**
 * SESSION — 경계를 가진 경험.
 *
 * 공간만이 아니라 시간·사건·기간까지 포괄한다. 하루짜리 축제도, 3주짜리
 * 부트캠프도 하나의 Session이다. 기준은 길이가 아니라 '떼어낼 수 있는가'다.
 *
 * body를 템플릿으로 고정하지 않고 ReactNode로 받는 이유는, 어떤 경험은 사진이
 * 중심이고 어떤 경험은 문장이 중심이기 때문이다. 공통 문법(Prose)은 유지하되
 * 구조는 콘텐츠마다 새로 짠다.
 */
/**
 * 목록과 본문이 함께 쓰는 한 장.
 *
 * 완성품 사진일 필요는 없다. 그 경험이 시작될 때의 상태를 보여 주는 편이
 * 더 정확할 때가 많다 — 만들기 전의 시안이라든지.
 */
export type Cover = {
  src: string
  /** 이 사진이 무엇을 보여주는지. 장식이 아니므로 빈 alt를 쓰지 않는다. */
  alt: string
  width: number
  height: number
  /**
   * 이 이미지에서 의미가 있는 자리(0..1의 비율).
   *
   * 연출값이 아니라 이미지에 대한 사실이다. 어디에 무엇이 찍혀 있는지는
   * 이 파일을 고른 사람만 알고, 표지든 목록이든 그 자리를 기준으로 보여 준다.
   */
  focus?: { x: number; y: number }
  /**
   * 잘라 쓸 수 없는 이미지인지.
   *
   * 초점과 같은 종류의 사실이다 — 연출이 아니라 이 파일이 무엇인지다. 사진은
   * 장면이라서 어디를 잘라도 여전히 그 장면의 일부지만, 어떤 이미지는 장면이
   * 아니라 «놓인 것»이다. 배경을 딴 시안 목업이 그렇고, 심볼이 그렇다. 그런
   * 것을 장면처럼 자르면 남는 것이 없다 — 목업은 목과 밑단이 한꺼번에 날아가
   * 셔츠의 가운데 토막만 남았고, 토끼는 귀와 입이 잘려 눈만 남은 가로줄이
   * 되었다.
   *
   * 이 사실을 아는 자리는 이 파일을 고른 사람뿐이다. 코드가 알파 채널을 열어
   * 보고 짐작할 수 있는 것도 아니고, 짐작해서 될 일도 아니다.
   */
  whole?: true
}

/**
 * 이 경험이 지면을 어떻게 쓰는지.
 *
 *   column  기본. 제목·메타데이터·본문이 정해진 판면에 앉는다.
 *   stage   본문이 판면 전체를 가져간다. 그 경험에만 있는 인터랙션이 필요할 때.
 *
 * 대부분의 SESSION은 column이다. stage는 형태 자체가 그 경험의 일부일 때만 쓴다 —
 * 남발하면 SESSION마다 다른 사이트가 되고, 그러면 공통 문법이 사라진다.
 */
export type SessionDisplay = 'column' | 'stage'

export type Session = {
  slug: string
  title: string
  subtitle?: string
  meta?: Meta
  /** 목록에 걸리는 한 줄. 없으면 목록은 제목만 보여준다. */
  excerpt?: string
  cover?: Cover
  /**
   * 이 기록에 실린 사진 전부. 실린 순서 그대로.
   *
   * `cover`와 다른 일을 한다. 표지는 이 기록을 대표하는 한 장이고, 이쪽은
   * 이 기록이 실제로 남긴 장면 전부다. 목록이 제목의 세로 줄이 아니라 장면이
   * 쌓인 판이 되면서 생긴 칸이다 — 사진이 여섯 장 남은 하루는 판에서도 여섯
   * 조각을 차지하고, 한 장뿐인 날은 한 조각만 차지한다. 그 차이를 고르게
   * 만들지 않는다. 남은 사진의 수가 곧 그날의 밀도다.
   *
   * 자동으로 긁어 오지 않는다. 본문의 React 트리를 훑어 `<Plate>`를 찾는
   * 방법도 있었지만, 그러면 조판을 바꿀 때마다 목록이 조용히 달라진다.
   * 어느 장면이 판에 오르는지는 그 기록을 쓴 사람이 정한다.
   *
   * 적지 않으면 표지 한 장만 오른다. 표지도 없으면 사진 없이 한 조각을
   * 차지한다 — 사진이 없다고 목록에서 사라지지는 않는다.
   */
  images?: readonly Cover[]
  display?: SessionDisplay
  /**
   * 읽기 전에 덧붙이는 배경.
   *
   * 본문을 대신 설명하지 않는다. 쓴 사람에게는 이미 있는데 처음 읽는
   * 사람에게는 보이지 않는 것 — 전에 쓰던 개인적인 규칙, 다른 기록에서
   * 이어진 생각, 어떤 자리를 고른 이유, 제목에 쓴 비유, 글이 쓰인 시각과
   * 일이 일어난 시각의 관계 — 만 먼저 놓는다.
   *
   * 요약이 아니다. 마지막 문장이 무엇을 회수하는지, 감정에 어떤 이름이
   * 붙는지, 읽으면서 알아챌 수 있는 연결은 여기 적지 않는다. 적으면 그것은
   * 좌표가 아니라 정답지가 된다.
   *
   * 길이를 맞추지 않는다. 앞에 서 있어야 할 맥락이 많은 글은 길고, 본문만으로
   * 읽히는 글은 두세 문단이면 끝난다.
   *
   * 없으면 그 자리는 그리지 않는다. 배경이 필요 없는 기록도 있다.
   */
  guide?: ReactNode
  body: ReactNode
  /**
   * 작은 판면(≤599px)을 위한 다른 배치.
   *
   * 내용을 줄이는 자리가 아니다. 같은 문장을 그대로 쓰되 장면을 합치고,
   * 커서를 전제로 만든 장치를 뺀다. 넓은 지면에서 각자 자리를 갖던 것들이
   * 한 줄 안에 모이면 «공간의 다양성»이 «장치의 연속»으로 바뀌기 때문이다.
   *
   * 적지 않으면 좁은 화면도 `body`를 그대로 쓴다. 대부분의 기록은 그래도 된다.
   */
  compact?: ReactNode
}

/**
 * 어디에서 어디까지인가.
 *
 * 버전 이름을 지어 붙이지 않는다. v2.3.0 같은 이름은 사람이 나중에 정한 것이고,
 * 실제로 일어난 일은 «이 커밋에서 저 커밋까지»다. 짧은 해시 일곱 자리는
 * 꾸며낸 데가 없는 유일한 이름이라 그것을 그대로 쓴다.
 */
export type Revision = {
  /** 시작한 자리. '8cd8123' */
  from: string
  /** 도착한 자리. '7d5e68d' */
  to: string
}

/**
 * 그 사이에 실제로 움직인 양.
 *
 * git이 세어 주는 숫자 그대로다. 여기에 «난이도»나 «중요도» 같은 값을 더하지
 * 않는다 — 그런 것은 사람이 매기는 인상이고, 인상은 본문이 말한다.
 *
 * 파일 수는 두지 않는다. 한동안 «27 FILES»로 적어 두었는데, 이 공간은
 * 메타데이터에 라벨을 붙이지 않기로 되어 있고 파일 수는 라벨 없이 읽히지
 * 않는다. 화면에 못 내보내는 값을 타입에 남겨 두면 그 값은 언젠가 라벨을
 * 데리고 돌아온다. 필요해지는 날 그때 더한다.
 */
export type Diff = {
  /** 몇 걸음에 갔는가. 막대의 눈금이 이 수만큼이다. */
  commits: number
  /** 더한 줄 */
  added: number
  /** 지운 줄 */
  removed: number
}

/**
 * CODE — 프로젝트가 옮겨 간 자리.
 *
 * SESSION이 경계를 가진 «경험»이라면 CODE는 경계를 가진 «변경»이다. 둘 다
 * 시작과 끝이 있지만, 세션의 경계는 기억이 정하고 코드의 경계는 두 개의
 * 해시가 정한다. 그래서 이쪽에는 지어낼 수 있는 값이 거의 없다.
 *
 * 세션과 달리 머리에 들어가는 항목이 미리 정해져 있다. 코드의 변경에는 실제로
 * 공통된 모양이 있기 때문이다 — 어디에서 어디까지, 몇 개의 커밋, 몇 줄이
 * 늘고 줄었는지. 그것을 매번 새로 짜는 것은 자유가 아니라 낭비다.
 *
 * 대신 body는 여전히 ReactNode다. 무엇을 고쳤는지는 정형이지만 무엇을
 * 잘못 짚었는지는 매번 다른 이야기라서, 그쪽까지 틀에 넣지는 않는다.
 */
export type Code = {
  slug: string
  title: string
  subtitle?: string
  /** 어느 저장소인가. 주소가 아니라 이름 하나면 된다. */
  repo?: string
  revision?: Revision
  diff?: Diff
  meta?: Meta
  /** 목록에 걸리는 한 줄. 이 업데이트로 무엇이 달라졌는지. */
  excerpt?: string
  body: ReactNode
  /** 작은 판면을 위한 다른 배치. 적지 않으면 body를 그대로 쓴다. */
  compact?: ReactNode
}

/**
 * THREAD — 이어지고 있는 생각.
 *
 * 완성된 분석이 아니므로 제목이 없어도 된다. 대신 날짜는 반드시 있다.
 * 생각을 이어붙인 순서 자체가 Thread의 형식이기 때문이다.
 */
/**
 * 이 생각이 지면에 앉는 방식.
 *
 *   note   기본. 날짜가 여백 칼럼에 앉고 본문이 그 옆에 온다.
 *   loud   한 문장짜리 생각. 판면 전체를 쓰고 크게 앉는다.
 *   aside  곁가지. 오른쪽 안쪽으로 물러나 좁고 낮게 앉는다.
 *
 * 길이가 형태를 정하지는 않는다. 어떤 자리에 놓고 싶은지를 글이 직접 고른다.
 */
export type ThreadForm = 'note' | 'loud' | 'aside'

export type Thread = {
  slug: string
  /** 'YYYY-MM-DD' */
  date: string
  title?: string
  form?: ThreadForm
  /**
   * 이 생각이 이어져 나온 앞의 글.
   *
   * 세 게시판 중 여기만 이 칸을 갖는다. 세션은 경계를 가진 경험이라 다음
   * 경험으로 이어지지 않고, 코드는 두 해시가 경계라 이어 붙이면 다른 변경이
   * 된다. 이어지는 것은 THREAD뿐이고, 그래서 이 게시판의 기호만 끝이 닫히지
   * 않고 점 셋으로 흘러간다.
   *
   * 지어내지 않는다. 본문이 앞 글을 실제로 가리킬 때만 적는다 — «지난 글에서
   * …까지는 정리했다»처럼. 글이 말하지 않은 관계를 화면이 만들면 그것은
   * 이어짐이 아니라 추천이 된다.
   */
  follows?: string
  body: ReactNode
  /**
   * 나중에 같은 생각으로 돌아와 덧붙인 것.
   *
   * 이어지는 중인 생각은 두 가지로 자란다. 옆으로 — 새 글이 앞 글을 물고
   * 나오는 것(follows). 그리고 안으로 — 이미 쓴 글에 나중에 한 문단이 붙는 것.
   * 앞의 것만 있으면 생각이 바뀔 때마다 글이 하나씩 늘고, 그러면 목록은
   * 결국 쌓이기만 한다.
   *
   * 덧붙여도 글은 원래 자리에 남는다. 생각은 그것을 한 시간에 속하고, 나중에
   * 한 말이 그 시간을 앞으로 끌어당기지 않는다. 8월에 한 생각은 8월에 있고
   * 9월에 덧붙인 문단은 그 글 안에서 9월이다.
   *
   * 날짜는 원래 날짜와 같은 여백 칼럼에 앉는다. 그래서 «덧붙임»이라고 적지
   * 않아도 된다 — 한 글에 날짜가 둘이면 무슨 일이 있었는지 이미 읽힌다.
   *
   * 앞선 것부터 적는다. 시간이 흐른 순서가 곧 읽는 순서다.
   */
  additions?: readonly ThreadAddition[]
}

/**
 * 덧붙인 한 조각.
 *
 * 본문을 고쳐 쓰는 것과 다르다. 고쳐 쓰면 처음에 무엇을 생각했는지가 사라지고,
 * 남는 것은 지금의 결론뿐이다. 여기 남기는 것은 그 사이의 거리다.
 */
export type ThreadAddition = {
  /** 'YYYY-MM-DD'. 글의 날짜보다 뒤여야 한다. */
  date: string
  body: ReactNode
}
