import styles from './Unvisited.module.css'

type Props = {
  /** 'CHAGEE' — 아침의 표에 있었고 끝내 가지 않은 이름. */
  name: string
}

/**
 * 가지 않은 곳.
 *
 * 사진이 없다. 실제로 가지 않았으니 이 자리에 걸 사진이 있을 수 없고, 분위기를
 * 위해 비슷한 가게의 사진을 걸면 그 순간 이 기록은 가 본 것이 된다.
 *
 * 그래서 아침의 표에 있던 글자만 한 번 더 나온다. 이번에는 아주 옅게.
 *
 * 움직이지 않는다.
 *
 * 이 지면의 다른 것들은 지나가면 위로 올라간다. 읽었기 때문이다. 이 이름은
 * 올라가지 않고 제자리에서 opacity만 0이 된다 — 가지 않은 곳은 하루 안에서
 * 어디로도 이동하지 않았다. 이 기록에서 자리를 뜨지 않고 사라지는 것은
 * 이것 하나뿐이다.
 *
 * 움직임을 줄이기로 한 화면에서는 옅은 채로 서 있는다. 이름이 사라지는 것이
 * 정보가 되어서는 안 된다 — 거기에 그런 곳이 있었다는 것은 사실이다.
 */
export function Unvisited({ name }: Props) {
  return (
    <p className={`mono ${styles.unvisited}`}>
      <span>{name}</span>
    </p>
  )
}
