import type { InterludeKind } from './Interlude'

/**
 * 대화 한 차례.
 *
 * 처음에는 이 타입이 「군단장은 본가에 있다」의 원고 파일 안에 있었다. 그
 * 기록에만 대화가 있었으니 그때는 맞는 자리였는데, 기차 안에서 오간 말을
 * 그대로 본문으로 쓰는 기록이 하나 더 생기면서 조판이 원고를 import하는
 * 모양이 되었다 — 새 기록의 대화를 그리기 위해 옛 기록의 원고 파일을
 * 읽어야 한다는 뜻이다. 그래서 형태만 이쪽으로 옮겼다. 원고는 여전히 각
 * 기록의 파일에 있고, 여기 있는 것은 그 원고들이 공통으로 가진 모양뿐이다.
 *
 * 말한 사람을 'me' 같은 열거값으로 두지 않고 화면에 적히는 글자 그대로
 * 받는다. 대화마다 상대가 다르고(TAB, JIPPY) 앞으로도 다를 텐데, 열거값을
 * 쓰면 조판이 «이 값은 TAB이라고 적는다»는 표를 들고 있게 된다. 그 표는
 * 기록이 하나 늘 때마다 한 줄씩 길어지고, 결국 조판이 원고의 등장인물을
 * 알게 된다. 이름은 원고가 말하는 편이 맞는다.
 */
export type ConversationTurn = {
  id: string
  /** 화면에 적히는 그대로. 'ME', 'TAB', 'JIPPY'. */
  speaker: string
  /**
   * 판면의 어느 쪽에 앉는지.
   *
   * 말한 사람과 따로 받는 이유는 둘이 같은 것이 아니기 때문이다. 이름은
   * 누구인지를 말하고 이 값은 어디에 앉는지를 말하는데, 한 기록 안에서
   * 같은 사람이 늘 같은 쪽에 앉는 것은 그 기록이 정한 규칙일 뿐이다.
   */
  side: 'left' | 'right'
  /**
   * 문단을 한 덩어리 문자열로 합치지 않고 배열로 나눠 둔다. PNG로 구울 때
   * 카드가 넘치면 «문단 → 문장» 순으로 끊을 자리를 찾는데, 그러려면 문단의
   * 경계가 원고에 남아 있어야 한다. 화면에서는 그대로 문단이 된다.
   */
  paragraphs: readonly string[]
  /** 대화 중에 사진을 보낸 자리. 장식이 아니라 그 문장이 가리키는 물건이다. */
  attachment?: {
    src: string
    alt: string
    width: number
    height: number
  }
  /** 이 말에 딸려 오는, 말이 아닌 것. 무엇이 올 수 있는지는 Interlude가 정한다. */
  interlude?: InterludeKind
}
