import type { Cover } from '../../content/types'

/**
 * 기록에 들어온 한 장.
 *
 * 사진과 영상이 같은 타입을 쓴다. 그날 찍을 때도 둘을 구분해서 찍은 것이
 * 아니라 그냥 계속 찍었고, 지면에서도 같은 자리를 받는다.
 *
 * 영상에는 자막이 따라온다. 여기 올라오는 영상은 대부분 소리가 내용의
 * 절반이라, 소리를 못 듣는 사람에게 그 자리가 «움직이는 사진»으로 줄어든다.
 * «[무대 음악]» 한 줄짜리 vtt라도 있어야 무엇이 들리고 있었는지는 전해진다.
 * 그래서 선택 항목으로 두지 않고 타입이 같이 요구한다.
 *
 * ContactSheet와 VerticalFeed가 이 타입을 함께 쓴다. 두 부품은 보여 주는
 * 방식이 반대지만 — 한 번에 많이 보느냐, 한 장씩 보느냐 — 들고 있는 것은
 * 같은 파일이다. 한쪽에 타입을 두고 다른 쪽이 그것을 가져다 쓰면, 나중에
 * 둘 중 하나를 지울 때 남은 쪽이 지워진 쪽에 매달린다.
 */
export type Shot = Cover & {
  video?: {
    /** 영상 파일의 주소. src는 이 영상의 첫 프레임 또는 대표 화면이 된다. */
    src: string
    /** 자막 파일(.vtt)의 주소. */
    captions: string
  }
}

/**
 * 한 장씩 보는 자리에 들어가는 것.
 *
 * note는 사진 설명이 아니라 그때 든 생각이다. 무엇이 찍혀 있는지는 사진이
 * 말하고 alt가 적는다. 모든 장에 붙이지 않는다 — 전부 붙으면 사진마다
 * 해설이 달린 것이 되고, 그러면 보는 일이 읽는 일로 바뀐다.
 */
export type FeedShot = Shot & {
  note?: string
}
